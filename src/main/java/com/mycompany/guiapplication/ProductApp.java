    private void jProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jProcessActionPerformed
        // TODO add your handling code here:
        String customerName = txtCustomerName.getText().trim();
        String productName = (String) comboBoxSelect.getSelectedItem();
        String priceStr = txtEnterPrice.getText().trim();

        if (customerName.isEmpty() || priceStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter customer name and price.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            double price = Double.parseDouble(priceStr);
            ProductCalculations calc = new ProductCalculations(price);

            double vat = calc.GetVat();
            double commission = calc.GetCommission();
            double total = calc.GetTotal();

        // Display in JOptionPane dialog matching exam sample
        String message = "Customer Name: " + customerName + "\n" +
                     "Product: " + productName + "\n" +
                     "VAT: R " + vat + "\n" +
                     "COMMISSION: R " + commission + "\n" +
                     "TOTAL: R " + total;

         javax.swing.JOptionPane.showMessageDialog(this, message, "Message", javax.swing.JOptionPane.INFORMATION_MESSAGE);

        // Save to data.txt file
        try (java.io.BufferedWriter writer = new java.io.BufferedWriter(new java.io.FileWriter("data.txt"))) {
            writer.write("DATA LOG\n");
            writer.write("Customer Name: " + customerName + "\n");
            writer.write("Product: " + productName + "\n");
            writer.write("VAT: R " + vat + "\n");
            writer.write("COMMISSION: R " + commission + "\n");
            writer.write("TOTAL: R " + total + "\n");
        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error saving file.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.", "Invalid Input", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jProcessActionPerformed

